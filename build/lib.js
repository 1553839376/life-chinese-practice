var BUILTIN_ART = {};
(function(){
  var i, c, inner;
  for (i = 0; i < CHARS.length; i++){
    c = CHARS[i];
    if (!c.a) continue;
    if (c.a === 'dots') inner = artDots(c.an || 1);
    else if (c.a === 'swatch'){
      inner = '<circle cx="60" cy="60" r="42" fill="' + c.an + '"' + (c.an === '#FFFFFF' ? ' stroke="#D8DEE9" stroke-width="5"' : '') + '/>';
    } else inner = ART[c.a] || '';
    if (inner && !BUILTIN_ART[c.c]) BUILTIN_ART[c.c] = inner;
  }
})();
